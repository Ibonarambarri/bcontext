/**
 * Integration catalog — the marketplace the hub renders and the allow-list
 * the install route checks against.
 *
 * Adding a provider (docs/integrations-nango.md):
 *   1. an entry here (`via: "nango"`, `nango_provider` = key in Nango's
 *      providers.yaml, `status: "available"`),
 *   2. an adapter file in `./nango/adapters/<key>.ts`, one line in `./nango/adapters/index.ts`,
 *   3. the integration created in Nango with `unique_key` === `key`.
 *
 * Popularity is a hand-ranked order, not a metric: Slack 1, GitHub 2,
 * Notion 3, Google Drive 4, Jira 5, Linear 6, Gmail 7, Google Calendar 8,
 * Confluence 9, Zoom 10, then the rest by how often a customer asks.
 */
import type {
  IntegrationCatalogEntry,
  IntegrationCategory,
} from "@bcontext-dev/contract/connectors/catalog";
import { oauthSetupFor } from "@/lib/nango/scopes";

const NANGO_LOGO = "https://app.nango.dev/images/template-logos";

function logo(provider: string): string {
  return `${NANGO_LOGO}/${provider}.svg`;
}

type Draft = Omit<IntegrationCatalogEntry, "logo_url" | "status" | "via" | "auth"> &
  Partial<Pick<IntegrationCatalogEntry, "logo_url" | "status" | "via" | "auth">> & {
    /** Nango provider key used for the logo even when the connector is native. */
    logo?: string;
  };

function native(d: Draft): IntegrationCatalogEntry {
  return {
    via: "native",
    auth: d.auth ?? "oauth2",
    status: d.status ?? "available",
    logo_url: d.logo_url ?? (d.logo ? logo(d.logo) : null),
    key: d.key,
    name: d.name,
    category: d.category,
    popularity: d.popularity,
    description: d.description,
    ...(d.nango_provider ? { nango_provider: d.nango_provider } : {}),
    ...(d.alt_key ? { alt_key: d.alt_key } : {}),
  };
}

function nango(d: Draft & { nango_provider: string }): IntegrationCatalogEntry {
  const auth = d.auth ?? "oauth2";
  const oauthSetup = auth === "oauth2" ? oauthSetupFor(d.nango_provider) : null;
  return {
    via: "nango",
    auth,
    status: d.status ?? "coming_soon",
    logo_url: d.logo_url ?? logo(d.logo ?? d.nango_provider),
    key: d.key,
    name: d.name,
    category: d.category,
    popularity: d.popularity,
    description: d.description,
    nango_provider: d.nango_provider,
    ...(d.alt_key ? { alt_key: d.alt_key } : {}),
    // Hybrid OAuth: every OAuth entry tells the customer how to bring its
    // own app (callback, scopes, console); `setup` says whether Bcontext's
    // shared app exists too. Absent on an instance without Nango.
    ...(oauthSetup ? { oauth_setup: oauthSetup } : {}),
  };
}

const soon = (d: Draft & { nango_provider: string }) => nango({ ...d, status: "coming_soon" });

