#!/usr/bin/env sh
# Writes .env.development.local from the running local Supabase stack
# (docs/ops/local-stack.md). Run after `supabase start`; needs the Supabase CLI
# and the Docker stack up. The API and the worker read it with
# `set -a && . ./.env.development.local && set +a` before `node dist/*.cjs`, so
# this file steers local development at the Docker stack while `.env.local`
# keeps pointing wherever it points. Delete the file to go back. The keys are
# stable per project, but generating them makes the choice explicit and
# reversible instead of hand-edited.
#
# The variables are written under their `NEXT_PUBLIC_*` names: `SUPABASE_URL`
# / `SUPABASE_ANON_KEY` / `APP_URL` are the primary names now and the
# `NEXT_PUBLIC_*` spellings are legacy aliases read as a fallback until
# 2026-12-31 (src/lib/env.ts).
#
# Never commit it. `.gitignore` already covers `.env*.local`.
set -eu
cd "$(dirname "$0")/.."

status="$(supabase status -o env 2>/dev/null)" || {
  echo "supabase is not running here; run: supabase start" >&2; exit 1
}
get() { printf '%s\n' "$status" | sed -n "s/^$1=\"\(.*\)\"$/\1/p"; }

api_url="$(get API_URL)"
anon="$(get ANON_KEY)"
service="$(get SERVICE_ROLE_KEY)"
db_url="$(get DB_URL)"
[ -n "$api_url" ] && [ -n "$anon" ] && [ -n "$service" ] && [ -n "$db_url" ] || {
  echo "could not read all keys from 'supabase status -o env'" >&2; exit 1
}

cat > .env.development.local <<ENV
# Generated by scripts/local-env.sh — local Docker Supabase, not production.
NEXT_PUBLIC_SUPABASE_URL=$api_url
NEXT_PUBLIC_SUPABASE_ANON_KEY=$anon
SUPABASE_SERVICE_ROLE_KEY=$service
# pg-boss worker and anything that speaks Postgres directly.
DATABASE_URL=$db_url
NEXT_PUBLIC_APP_URL=http://localhost:3000
# Internal secret of POST /realtime/broadcast; any value works, it just has
# to match across processes.
REALTIME_SECRET=local-dev-realtime-secret
# The API process on :4000 — bcontext-web proxies routes there (build-time!)
# and the browser opens its realtime sockets there.
API_ORIGIN=http://localhost:4000
NEXT_PUBLIC_REALTIME_URL=ws://localhost:4000
ENV
echo "wrote .env.development.local -> $api_url"
