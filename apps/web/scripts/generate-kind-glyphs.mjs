#!/usr/bin/env node
/**
 * Generate the canvas glyph for every node kind FROM the installed lucide
 * package.
 *
 * The graph draws a kind's icon inside its node, and it has to be the same
 * icon the lists draw (`src/components/node-kind-icon.ts`) — that shared
 * vocabulary is the point. But lucide-react closes over its path data inside
 * `createLucideIcon`, so a WebGL canvas cannot get at it, and hand-copying
 * ten path strings into the repo would drift silently the first time lucide
 * reshapes a glyph.
 *
 * So the paths are DERIVED: this script reads the icon modules out of
 * node_modules and writes `src/lib/graph/kind-glyphs.generated.ts`. The
 * committed output is checked against a fresh run by
 * `kind-glyphs.generated.test.ts`, so a lucide bump that changes a glyph
 * fails the suite instead of quietly diverging from the rest of the app.
 *
 *   npm run generate:kind-glyphs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { createRequire } from "node:module";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
// Resolved like any import: in the monorepo lucide-react is hoisted to the root.
const lucideDir = dirname(createRequire(join(root, "package.json")).resolve("lucide-react/package.json"));

/**
 * kind → lucide module name. Must mirror NODE_KIND_ICONS; the generated
 * test's kind list is what keeps the two in step.
 */
export const GLYPH_SOURCES = {
  doc: "file-text",
  task: "check-square-2",
  decision: "gavel",
  meeting: "users-2",
  bug: "bug",
  adr: "scroll-text",
  entity: "layers",
  skill: "wrench",
  data: "table-2",
  credential: "key-round",
  goal: "target",
  // Not a node kind: the glyph a tag hub carries, matching the tag picker.
  tag: "hash",
};

/**
 * Pull the `iconNode` array literal out of an icon module and evaluate it.
 * Some names are aliases that only re-export another module (`users-2` →
 * `users-round`), so the re-export chain is followed first.
 */
function readIconNode(moduleName, seen = new Set()) {
  if (seen.has(moduleName)) throw new Error(`${moduleName}: circular re-export`);
  seen.add(moduleName);
  const source = readFileSync(
    join(lucideDir, "dist/esm/icons", `${moduleName}.js`),
    "utf8",
  );
  const alias = /export\s*\{\s*default\s*\}\s*from\s*['"]\.\/([\w-]+)\.js['"]/.exec(source);
  if (alias) return readIconNode(alias[1], seen);
  const marker = "createLucideIcon(";
  const callStart = source.indexOf(marker);
  if (callStart < 0) throw new Error(`${moduleName}: no createLucideIcon call`);
  const arrayStart = source.indexOf("[", callStart);
  if (arrayStart < 0) throw new Error(`${moduleName}: no iconNode array`);
  let depth = 0;
  let arrayEnd = -1;
  for (let index = arrayStart; index < source.length; index++) {
    const char = source[index];
    if (char === "[") depth++;
    else if (char === "]") {
      depth--;
      if (depth === 0) { arrayEnd = index + 1; break; }
    }
  }
  if (arrayEnd < 0) throw new Error(`${moduleName}: unbalanced iconNode array`);
  const literal = source.slice(arrayStart, arrayEnd);
  // Plain data (string keys, string values) from a package we installed.
  const iconNode = new Function(`return ${literal};`)();
  if (!Array.isArray(iconNode) || iconNode.length === 0) {
    throw new Error(`${moduleName}: iconNode did not evaluate to elements`);
  }
  return iconNode;
}

const ATTRIBUTE_ORDER = ["d", "x", "y", "width", "height", "rx", "ry", "cx", "cy", "r", "x1", "y1", "x2", "y2", "points", "fill"];

function serializeElement([tag, attributes]) {
  const entries = Object.entries(attributes)
    // `key` is React reconciliation bookkeeping, not SVG.
    .filter(([name]) => name !== "key")
    .sort(([a], [b]) => {
      const rankA = ATTRIBUTE_ORDER.indexOf(a);
      const rankB = ATTRIBUTE_ORDER.indexOf(b);
      return (rankA < 0 ? 99 : rankA) - (rankB < 0 ? 99 : rankB) || a.localeCompare(b);
    })
    .map(([name, value]) => `${name}="${String(value).replace(/"/g, "&quot;")}"`);
  return `<${tag}${entries.length > 0 ? ` ${entries.join(" ")}` : ""}/>`;
}

export function buildGlyphBodies() {
  const bodies = {};
  for (const [kind, moduleName] of Object.entries(GLYPH_SOURCES).sort(([a], [b]) => a.localeCompare(b))) {
    bodies[kind] = readIconNode(moduleName).map(serializeElement).join("");
  }
  return bodies;
}

export function renderModule(bodies) {
  const entries = Object.entries(bodies)
    .map(([kind, body]) => `  ${kind}: ${JSON.stringify(body)},`)
    .join("\n");
  return `// GENERATED by scripts/generate-kind-glyphs.mjs — do not edit by hand.
// Run \`npm run generate:kind-glyphs\` after bumping lucide-react.
//
// The inner SVG markup of every node-kind glyph, lifted from the same lucide
// icons the lists render (src/components/node-kind-icon.ts) so the canvas and
// the rest of the app cannot disagree about what a decision looks like.

export const KIND_GLYPH_BODIES = {
${entries}
} as const;

export type GlyphKey = keyof typeof KIND_GLYPH_BODIES;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = join(root, "src/lib/graph/kind-glyphs.generated.ts");
  writeFileSync(target, renderModule(buildGlyphBodies()), "utf8");
  console.log(`wrote ${target}`);
}
