/**
 * Writes src/api/routes.generated.ts: one import per `src/app/**` route module
 * (the `route.ts` file convention, `Request → Response` handlers) and the Hono
 * path it answers on. Run by `build:api` / `npm run gen:api-routes` and checked
 * by `src/api/routes.generated.test.ts`, so the table cannot drift from the
 * filesystem — a route file that exists and is not served by the API process
 * is the failure this exists to make loud. `src/api/app.ts` mounts `ROUTES`
 * verbatim; there is no per-group opt-in anywhere else.
 *
 * Also writes the path-only tables (`src/api/paths.generated.ts` and the
 * contract's `api-paths.generated.ts`) that bcontext-web uses to build its
 * proxy rewrites. Needs nothing but the checkout (no env, no DB).
 */
import { readdirSync, statSync, writeFileSync, readFileSync } from "node:fs";
import { join, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const appDir = join(root, "src/app");

function walk(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full, out);
    else if (entry === "route.ts") out.push(full);
  }
  return out;
}

const METHODS = ["GET", "POST", "PUT", "PATCH", "DELETE", "OPTIONS"];

const entries = walk(appDir)
  .map((file) => {
    const nextPath = "/" + relative(appDir, dirname(file)).split("/").filter(Boolean).join("/");
    const honoPath = nextPath.replace(/\[([^\]]+)\]/g, ":$1");
    const source = readFileSync(file, "utf8");
    // A handler may be a sync function too (`export function OPTIONS`); the
    // adapter serves it, so leaving it out of the table drops the method here.
    const methods = METHODS.filter((m) => new RegExp(`^export (const|async function|function) ${m}\\b`, "m").test(source));
    const importPath = "@/app" + nextPath + "/route";
    return { nextPath, honoPath, methods, importPath };
  })
  // Registration order is match order in Hono. `/api/activity/:id` and
  // `/api/activity/facets` are both GET; sorted alphabetically `:id` comes
  // first (":" < "f") and `facets` would be served as an id. So at every
  // depth a literal segment sorts before a parameter, and among literals
  // alphabetically — the same rule filesystem routers apply.
  .sort((a, b) => compareRoutes(a.honoPath, b.honoPath));

function compareRoutes(a, b) {
  const as = a.split("/"), bs = b.split("/");
  for (let i = 0; i < Math.max(as.length, bs.length); i++) {
    const x = as[i] ?? "", y = bs[i] ?? "";
    if (x === y) continue;
    const xp = x.startsWith(":"), yp = y.startsWith(":");
    if (xp !== yp) return xp ? 1 : -1;
    return x.localeCompare(y);
  }
  return 0;
}

const lines = [
  "// GENERATED by scripts/gen-api-routes.mjs — do not edit. Re-run: npm run gen:api-routes",
  'import type { RouteModule } from "./adapter";',
  "",
  ...entries.map((e, i) => `import * as r${i} from "${e.importPath}";`),
  "",
  "export const ROUTES: ReadonlyArray<{ path: string; methods: readonly string[]; module: RouteModule }> = [",
  ...entries.map((e, i) => `  { path: ${JSON.stringify(e.honoPath)}, methods: ${JSON.stringify(e.methods)}, module: r${i} as unknown as RouteModule },`),
  "];",
  "",
];
writeFileSync(join(root, "src/api/routes.generated.ts"), lines.join("\n"));

// Paths alone, no imports: bcontext-web reads the contract copy in its
// next.config.ts to build the proxy rewrites without evaluating a single route
// module. "These paths are the API" is a promise the web side builds its proxy
// on, and it has no other way to know.
const pathsSource =
  [
    "// GENERATED by scripts/gen-api-routes.mjs — do not edit. Re-run: npm run gen:api-routes",
    "export const ROUTE_PATHS: readonly string[] = [",
    ...entries.map((e) => `  ${JSON.stringify(e.honoPath)},`),
    "];",
    "",
  ].join("\n");
writeFileSync(join(root, "src/api/paths.generated.ts"), pathsSource);
writeFileSync(join(root, "../../packages/contract/src/api-paths.generated.ts"), pathsSource);
console.log(`api routes: ${entries.length} modules, ${entries.reduce((n, e) => n + e.methods.length, 0)} handlers`);
