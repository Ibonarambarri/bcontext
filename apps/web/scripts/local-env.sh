#!/usr/bin/env sh
# Writes .env.development.local from the running local Supabase stack.
#
# Next loads `.env.development.local` above `.env.local` in `next dev`, so this
# file steers local development at the Docker stack while `.env.local` keeps
# pointing wherever it points (e.g. another Supabase). Delete
# the file to go back. Regenerate after `supabase start` — the keys are stable
# but this makes the choice explicit and reversible instead of hand-edited.
#
# Never commit it. `.gitignore` already covers `.env*.local`.
set -eu
cd "$(dirname "$0")/.."

status="$(supabase status --workdir ../api -o env 2>/dev/null)" || {
  echo "supabase is not running here; run: supabase start" >&2; exit 1
}
get() { printf '%s\n' "$status" | sed -n "s/^$1=\"\(.*\)\"$/\1/p"; }

api_url="$(get API_URL)"
anon="$(get ANON_KEY)"
service="$(get SERVICE_ROLE_KEY)"
[ -n "$api_url" ] && [ -n "$anon" ] && [ -n "$service" ] || {
  echo "could not read all keys from 'supabase status -o env'" >&2; exit 1
}

cat > .env.development.local <<ENV
# Generated by scripts/local-env.sh — local Docker Supabase, not production.
NEXT_PUBLIC_SUPABASE_URL=$api_url
NEXT_PUBLIC_SUPABASE_ANON_KEY=$anon
# Only scripts/session-cookie.mjs reads it (creates the local test user).
SUPABASE_SERVICE_ROLE_KEY=$service
NEXT_PUBLIC_APP_URL=http://localhost:3000
# The API process on :4000 — web proxies routes there (build-time!) and the
# browser opens its realtime sockets there. Comment both out to run web alone.
API_ORIGIN=http://localhost:4000
NEXT_PUBLIC_REALTIME_URL=ws://localhost:4000
ENV
echo "wrote .env.development.local -> $api_url"
