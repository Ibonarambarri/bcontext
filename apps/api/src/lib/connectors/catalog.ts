const BY_KEY = new Map(INTEGRATION_CATALOG.map((entry) => [entry.key, entry]));

export function catalogEntry(key: string): IntegrationCatalogEntry | null {
  return BY_KEY.get(key) ?? null;
}

export function listCatalog(opts: { category?: IntegrationCategory; query?: string } = {}): IntegrationCatalogEntry[] {
  const q = opts.query?.trim().toLowerCase();
  return INTEGRATION_CATALOG.filter((entry) => {
    if (opts.category && entry.category !== opts.category) return false;
    if (q && !`${entry.name} ${entry.key} ${entry.description}`.toLowerCase().includes(q)) return false;
    return true;
  }).sort((a, b) => a.popularity - b.popularity);
}

/** Is this a connector the install route may create? */
export function isInstallable(key: string): boolean {
  const entry = BY_KEY.get(key);
  return !!entry && entry.status === "available";
}

export function isNangoBacked(key: string): boolean {
  return BY_KEY.get(key)?.via === "nango";
}
